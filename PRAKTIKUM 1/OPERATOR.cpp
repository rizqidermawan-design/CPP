#include <iostream>
using namespace std;

int main() {
    int a = 10;
    int b = 3;
    int c = 2;

    cout << "Penjumlahan : " << a + b / c << endl;
    cout << "Pengurangan : " << a - b << endl;
    cout << "Perkalian   : " << a * b / c << endl;
    cout << "Pembagian   : " << a / b << endl;
    cout << "Sisa bagi   : " << a % b << endl;
    cout << " hasil      : " << a + b / c << endl;
    cout << " hasil      : " << a * b / c << endl;
    cout << " hasil      : " << a / b * c << endl;
    return 0;
}